// Bundles server/chat.ts (and the assistant engine it uses) into a single,
// dependency-free api/chat.js that Vercel runs as a Function. The header
// records a hash of the sources; a test fails if the bundle is stale.
//
//   npm run build:api

import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { build } from "vite";
import { sourceHash } from "./lib/api-sources.ts";

const root = resolve(import.meta.dirname, "..");
const outDir = mkdtempSync(join(tmpdir(), "api-build-"));

await build({
  root,
  configFile: false,
  logLevel: "warn",
  ssr: { noExternal: true },
  build: {
    ssr: join(root, "server/chat.ts"),
    outDir,
    emptyOutDir: true,
    minify: false,
    target: "node20",
    rollupOptions: { output: { format: "es", entryFileNames: "chat.js" } },
  },
});

const code = readFileSync(join(outDir, "chat.js"), "utf8");
rmSync(outDir, { recursive: true, force: true });
const header = [
  "// Generated by `npm run build:api` from server/chat.ts. Do not edit.",
  `// source-hash: ${sourceHash(root)}`,
  "",
].join("\n");
writeFileSync(join(root, "api/chat.js"), header + code);
console.log("Wrote api/chat.js");
